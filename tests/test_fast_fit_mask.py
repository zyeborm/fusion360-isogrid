"""Fast fit-search surrogate: no external dependencies, no exact trial Booleans."""
import time
import unittest
from unittest.mock import patch
import pathlib
import sys
sys.path.insert(0,str(pathlib.Path(__file__).resolve().parents[1]))
import geometry
import fitting
import fast_fit
from test_curved_dxf_regression import test_regions


class FastFitMaskTests(unittest.TestCase):
    def test_hole_and_perimeter_setbacks(self):
        region=geometry.Region([
            ([(0,0),(10,0),(10,10),(0,10)], True),
            ([(4,4),(6,4),(6,6),(4,6)], False)])
        mask=fast_fit.Mask([region],1.5,.3,.5)
        self.assertTrue(mask.contains(1,1))
        self.assertFalse(mask.contains(.1,5))
        self.assertFalse(mask.contains(5,5))
        self.assertFalse(mask.contains(5,6.2))
        self.assertTrue(mask.contains(5,7))

    def test_minimum_pitch_and_circular_void_on_actual_curved_region(self):
        mask=fast_fit.Mask(test_regions(),1.7,.3,.3)
        self.assertFalse(mask.contains(1.664676094,1.088084374))
        self.assertTrue(mask.contains(-10.,2.))
        self.assertFalse(mask.contains(-30.,2.))

    def test_search_bypasses_expensive_final_geometry(self):
        regions=test_regions()
        settings=dict(pitch=2.,rib=.2,perimeter=.3,holeclear=.3,
                      dx=0.,dy=0.,corner=.15,nodehole=.3,minfraction=5.,
                      angle=0.,backend='auto')
        start=time.perf_counter()
        with patch.object(geometry,'make_pockets',side_effect=AssertionError(
                'Exact final geometry must not be generated by fit search')):
            results=fitting.find_fits(regions,settings,pitch_min=1.7,
                                      pitch_max=2.8,evaluations=1000)
        elapsed=time.perf_counter()-start
        self.assertGreaterEqual(len(results),4)
        self.assertTrue(all(1.7<=f.pitch<=2.8 for f in results))
        self.assertLess(elapsed,20.,'1000 trials must complete interactively')
        self.assertEqual(results[-1].label,'Maximum removal')
        print('1000 fast trials in %.3f seconds'%elapsed)


if __name__=='__main__':unittest.main()
