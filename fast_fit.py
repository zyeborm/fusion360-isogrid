"""Fast, approximate scoring mask for isogrid layout search.

Source curves are rasterised ONCE from their existing preview polygons. The
mask is diagnostic/scoring-only: the selected layout is always generated by
the exact geometry engine. No external libraries or Fusion API calls.
"""
from __future__ import annotations
import math
import geometry

SQRT2 = math.sqrt(2.)
INF = 1e8


def _scanline(poly, y):
    crossings = []
    ax, ay = poly[-1]
    for bx, by in poly:
        if (ay <= y < by) or (by <= y < ay):
            crossings.append(ax + (y-ay)*(bx-ax)/(by-ay))
        ax, ay = bx, by
    crossings.sort()
    return crossings


def _fill_row(dest, offset, width, x0, step, crossings):
    for left, right in zip(crossings[::2], crossings[1::2]):
        a = max(0, math.ceil((left - x0)/step))
        b = min(width, math.ceil((right - x0)/step))
        if b > a:
            dest[offset+a:offset+b] = b'\x01'*(b-a)


def _distance_to_invalid(invalid, width, height):
    """Two-pass octile distance transform, O(pixels), with no dependencies."""
    # Each cell contains the approximate distance in pixel units to an invalid
    # centre. Octile distance is a slight overestimate of Euclidean distance.
    d = [0. if invalid[i] else INF for i in range(width*height)]
    diag=SQRT2
    for y in range(height):
        row=y*width
        for x in range(width):
            p=row+x
            a=d[p]
            if x: a=min(a, d[p-1]+1.)
            if y:
                a=min(a,d[p-width]+1.)
                if x: a=min(a,d[p-width-1]+diag)
                if x+1<width: a=min(a,d[p-width+1]+diag)
            d[p]=a
    for y in range(height-1,-1,-1):
        row=y*width
        for x in range(width-1,-1,-1):
            p=row+x
            a=d[p]
            if x+1<width:a=min(a,d[p+1]+1.)
            if y+1<height:
                a=min(a,d[p+width]+1.)
                if x: a=min(a,d[p+width-1]+diag)
                if x+1<width:a=min(a,d[p+width+1]+diag)
            d[p]=a
    return d


# Area-uniform deterministic triangle quadrature: 16 sample locations.
SAMPLES=tuple((1-math.sqrt((i+.5)/4),
               math.sqrt((i+.5)/4)*(1-(j+.5)/4),
               math.sqrt((i+.5)/4)*((j+.5)/4))
              for i in range(4) for j in range(4))


class Mask:
    """Constant-time polygonal region and setback queries for fit trials."""
    def __init__(self, regions, pitch_min, perimeter, void_clearance):
        box=geometry.face_bounds(regions)
        maxmargin=max(perimeter,void_clearance)
        step=min(pitch_min/20., maxmargin/5. if maxmargin>0 else pitch_min/20.)
        # Avoid excess memory on very large parts. Coarse grids are still a
        # useful first-stage ranking, and never used for final sketch geometry.
        step=max(step, .0005)
        pad=maxmargin+pitch_min
        x0,y0,x1,y1=box
        width=math.ceil((x1-x0+2*pad)/step)+1
        height=math.ceil((y1-y0+2*pad)/step)+1
        if width*height>250000:
            step*=math.sqrt(width*height/250000.)
            width=math.ceil((x1-x0+2*pad)/step)+1
            height=math.ceil((y1-y0+2*pad)/step)+1
        self.x0=x0-pad;self.y0=y0-pad;self.step=step
        self.width=width;self.height=height
        total=width*height
        exterior=bytearray(b'\x01')*total
        holes=bytearray(total)
        for region in regions:
            this_exterior=bytearray(total)
            for poly,outer in region.loops:
                target=this_exterior if outer else holes
                # Each polygon's edges are scanned once per grid row, rather
                # than running expensive point-in-NURBS predicates per pixel.
                ys=[p[1] for p in poly]
                start=max(0,math.ceil((min(ys)-self.y0)/step))
                end=min(height,math.ceil((max(ys)-self.y0)/step))
                for j in range(start,end):
                    y=self.y0+j*step
                    _fill_row(target,j*width,width,self.x0,step,_scanline(poly,y))
            for k in range(total):
                exterior[k] &= this_exterior[k]
        outer_distance=_distance_to_invalid(bytearray(1-v for v in exterior),width,height)
        hole_distance=_distance_to_invalid(holes,width,height) if any(holes) else None
        # A small safety cushion accounts for pixel-centre quantisation and
        # the octile distance transform. The mask is a conservative surrogate.
        edge_min=perimeter/step+0.75
        hole_min=void_clearance/step+0.75
        self.valid=bytearray(1 if exterior[i] and outer_distance[i]>=edge_min
            and (hole_distance is None or hole_distance[i]>=hole_min)
            else 0 for i in range(total))

    def contains(self,x,y):
        i=round((x-self.x0)/self.step)
        j=round((y-self.y0)/self.step)
        return (0<=i<self.width and 0<=j<self.height and
                self.valid[j*self.width+i]!=0)

    def fraction(self,pocket):
        a,b,c=pocket[:3]
        # Fast candidate pockets are the three corners of a pre-inset triangle,
        # not an arc-rich finished sketch.
        total=0
        for u,v,w in SAMPLES:
            total+=self.contains(u*a[0]+v*b[0]+w*c[0],
                                 u*a[1]+v*b[1]+w*c[1])
        return total/len(SAMPLES)

    def circle_fits(self,center,radius):
        x,y=center
        return (self.contains(x,y) and all(
            self.contains(x+radius*math.cos(a),y+radius*math.sin(a))
            for a in (0.,math.pi/4,math.pi/2,3*math.pi/4,math.pi,
                      5*math.pi/4,3*math.pi/2,7*math.pi/4)))
